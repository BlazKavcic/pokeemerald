#!/usr/bin/env python3
"""Generates include/showdown/sd_charmap.h (ASCII -> Emerald text codes) from charmap.txt."""
import re
from pathlib import Path

root = Path(__file__).resolve().parents[1]
text = (root / "charmap.txt").read_text(encoding="utf-8")
table = {}
for line in text.splitlines():
    m = re.match(r"^'(\\?.)'\s*=\s*([0-9A-Fa-f]{2})\s*$", line)
    if not m:
        continue
    ch = m.group(1)
    if len(ch) == 2 and ch[0] == "\\":
        ch = ch[1]
    table.setdefault(ch, int(m.group(2), 16))

unknown = table.get("?", 0xAC)
vals = []
for i in range(128):
    c = chr(i)
    vals.append(table.get(c, unknown) if 32 <= i < 127 else 0)
missing = "".join(chr(i) for i in range(32, 127) if chr(i) not in table)
out = (
    "// GENERATED by tools/showdown_charmap.py from charmap.txt: ASCII -> Emerald text codes.\n"
    "#ifndef GUARD_SHOWDOWN_SD_CHARMAP_H\n#define GUARD_SHOWDOWN_SD_CHARMAP_H\n\n"
    "static const u8 sAsciiToEmerald[128] = {\n    "
    + ", ".join(f"0x{v:02X}" for v in vals)
    + "\n};\n\n#endif\n"
)
(root / "include" / "showdown" / "sd_charmap.h").write_text(out)
print("charmap ok; unmapped ascii:", repr(missing))
